import { ReactNode, useState } from "react";
import { AnimatePresence, motion } from "framer-motion";
import { BarChart3, BookOpen, FlaskConical, Home, Info, LayoutDashboard, Menu, MessageSquareText, X } from "lucide-react";
import { Link, useLocation } from "../router";
import { api } from "../services/api";
import { cx, Logo, useApi } from "./ui";

const NAV = [
  { to: "/dashboard", label: "Dashboard", icon: LayoutDashboard },
  { to: "/chat", label: "Ask CampusSage", icon: MessageSquareText },
  { to: "/library", label: "Policy Library", icon: BookOpen },
  { to: "/lab", label: "Prompt Lab", icon: FlaskConical },
  { to: "/evaluation", label: "Evaluation", icon: BarChart3 },
  { to: "/about", label: "About & Team", icon: Info },
];

function SystemStatus() {
  const { data, error } = useApi(() => api.health(), []);
  if (error) return <div className="rounded-xl bg-rose-500/10 p-3 text-xs text-rose-200">API offline</div>;
  if (!data) return null;
  return (
    <div className="rounded-xl bg-white/5 p-3 text-xs text-slate-300">
      <div className="flex items-center gap-2 font-medium text-white">
        <span className={cx("h-2 w-2 rounded-full", data.demo_mode ? "bg-amber-400" : "bg-emerald-400")} />
        {data.demo_mode ? "Demo mode (no LLM)" : `LLM: ${data.model}`}
      </div>
      <div className="mt-1 text-slate-400">
        {data.documents} documents · {data.retrieval.chunks} chunks · {data.retrieval.backend === "chroma" ? "ChromaDB" : "TF-IDF"}
      </div>
    </div>
  );
}

function NavList({ onNavigate }: { onNavigate?: () => void }) {
  const { path } = useLocation();
  return (
    <nav className="flex flex-col gap-1">
      {NAV.map(({ to, label, icon: Icon }) => {
        const active = path === to;
        return (
          <Link
            key={to}
            to={to}
            onClick={onNavigate}
            className={cx(
              "flex items-center gap-3 rounded-xl px-3 py-2.5 text-sm font-medium transition-colors",
              active ? "bg-white text-navy-900" : "text-slate-300 hover:bg-white/10 hover:text-white",
            )}
          >
            <Icon size={18} />
            {label}
          </Link>
        );
      })}
    </nav>
  );
}

export function DemoModeBanner() {
  const { data } = useApi(() => api.health(), []);
  if (!data?.demo_mode) return null;
  return (
    <div className="mb-5 rounded-xl border border-amber-200 bg-amber-50 px-4 py-2.5 text-sm text-amber-900">
      <strong className="font-semibold">Demo mode:</strong>{" "}
      {data.demo_reason ??
        "no LLM API key is configured, so answers are extracted word for word from the policy text by a local fallback, not generated by a language model."}
    </div>
  );
}

export default function AppLayout({ children }: { children: ReactNode }) {
  const [open, setOpen] = useState(false);
  return (
    <div className="min-h-screen lg:pl-64">
      {/* desktop sidebar */}
      <aside className="fixed inset-y-0 left-0 z-30 hidden w-64 flex-col justify-between bg-navy-900 p-4 lg:flex">
        <div>
          <Link to="/" className="mb-8 block px-2 pt-2">
            <Logo light />
          </Link>
          <NavList />
        </div>
        <div className="space-y-3">
          <SystemStatus />
          <Link to="/" className="flex items-center gap-2 px-2 text-xs text-slate-400 hover:text-white">
            <Home size={14} /> Back to home
          </Link>
        </div>
      </aside>

      {/* mobile top bar */}
      <header className="sticky top-0 z-30 flex items-center justify-between border-b border-line bg-white/90 px-4 py-3 backdrop-blur lg:hidden">
        <Link to="/">
          <Logo />
        </Link>
        <button className="btn-ghost btn-sm" aria-label="Open menu" onClick={() => setOpen(true)}>
          <Menu size={18} />
        </button>
      </header>
      <AnimatePresence>
        {open && (
          <>
            <motion.div className="fixed inset-0 z-40 bg-navy-950/40 lg:hidden" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onClick={() => setOpen(false)} />
            <motion.aside
              className="fixed inset-y-0 left-0 z-50 flex w-72 flex-col justify-between bg-navy-900 p-4 lg:hidden"
              initial={{ x: -300 }}
              animate={{ x: 0 }}
              exit={{ x: -300 }}
              transition={{ type: "tween", duration: 0.2 }}
            >
              <div>
                <div className="mb-8 flex items-center justify-between px-2 pt-2">
                  <Logo light />
                  <button className="text-slate-300" aria-label="Close menu" onClick={() => setOpen(false)}>
                    <X size={20} />
                  </button>
                </div>
                <NavList onNavigate={() => setOpen(false)} />
              </div>
              <SystemStatus />
            </motion.aside>
          </>
        )}
      </AnimatePresence>

      <main className="mx-auto max-w-6xl px-4 py-6 sm:px-6 lg:px-10 lg:py-10">{children}</main>
    </div>
  );
}
